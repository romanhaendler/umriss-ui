export default function WhyRowActions() {
  return (
    <>
      <h3>The quiet gesture</h3>
      <p>
        Actions at the row stand at rest in the secondary type and become the accent as soon as the
        row is meant: under the pointer, or with the focus inside it. They never vanish. Revealing
        them on pointer contact alone would pass every screenshot and would be invisible to everyone
        who works without a mouse.
      </p>

      <h3>Two in the row, from three on in the menu</h3>
      <p>
        Up to two actions stand there as buttons; from three on, all of them stand in a menu. A
        mixture of buttons and a menu would give the column a different width depending on the
        number, and an action would wander out of the row into the menu as soon as a third one was
        added – whoever found it in one place yesterday would look for it in another today.
      </p>

      <h3>A bulk action always receives a list</h3>
      <p>
        At the row, a list made of it; in the table toolbar, the selection within the filtered set.
        An action is written once and stands in both places, and the function behind it does not
        distinguish where it was called from. That is how three deleted rows are one confirmation
        and not three.
      </p>
    </>
  );
}
