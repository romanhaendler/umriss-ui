import { open, csv, sel, clickExport, ROWS } from "./lib.mjs";
const ids = (s) => s.split(/\r?\n(?=R\d)/).slice(1).map((l) => l.slice(0, 4));
const h = await open({ server: true, pageSize: 5 });
const P = h.page; const ev = async (f) => { await P.evaluate(f); await P.waitForTimeout(250); };
console.log("page1 asCsv:", ids(await csv(P)).join(" "), "| button:", await P.getByRole("button", { name: /^Export/ }).first().innerText());
await ev(() => window.t.setPage(3));
console.log("page3 asCsv:", ids(await csv(P)).join(" "));
const n1 = ids(await clickExport(P));
console.log("export click page3 (no exportRows, since I did give it):", n1.length, n1.slice(0, 3));
await ev(() => window.t.setSearch("alpha"));
console.log("search alpha: export n=", ids(await clickExport(P)).length, JSON.stringify(await P.evaluate(() => window.exportReq)));
await ev(() => { window.t.setSearch(""); window.t.toggleSort("price"); window.t.setPage(1); });
const e = ids(await clickExport(P));
console.log("sort price export:", e.length, e.slice(0, 6).join(" "), JSON.stringify(await P.evaluate(() => window.exportReq)));
await ev(() => window.t.selection.set(["R001", "R030"], true));
console.log("selection other pages copy:", JSON.stringify(await sel(P)), "count", await P.evaluate(() => window.t.selection.count));
console.log("button label:", await P.getByRole("button", { name: /^Export/ }).first().innerText());
console.log(h.logs);
await h.close();
