import { open, csv, sel, clickExport, ROWS } from "./lib.mjs";
const ids = (s) => s.split(/\r?\n(?=R\d)/).slice(1).map((l) => l.slice(0, 4));
const h = await open({ groupBy: true, detail: true });
const P = h.page;
const ev = async (f) => { await P.evaluate(f); await P.waitForTimeout(200); };
await ev(() => window.t.setGrouping(["grp"]));
const screen = async () => P.evaluate(() => [...document.querySelectorAll("tbody tr")].map((r) => r.innerText.replace(/\s+/g, " ").slice(0, 40)));
console.log("grouped asCsv ids:", ids(await csv(P)).join(" "));
console.log("screen rows:", (await screen()).slice(0, 8));
await ev(() => window.t.foldAll());
console.log("folded asCsv count:", ids(await csv(P)).length, "screen:", await screen());
await ev(() => { window.t.unfoldAll(); window.t.setGrouping(["grp", "sub"]); window.t.toggleSort("price"); });
console.log("2-level sort price:", ids(await csv(P)).join(" "));
await ev(() => { window.t.setGrouping(["decade"]); });
console.log("groupBy decade asCsv header:", (await csv(P)).split("\r\n")[0]);
console.log("groupBy ids:", ids(await csv(P)).slice(0, 10).join(" "));
await ev(() => { window.t.setGrouping([]); window.t.toggleRow("R001"); });
console.log("detail open asCsv cols:", (await csv(P)).split("\r\n")[0].split(",").length);
console.log(h.logs);
await h.close();
