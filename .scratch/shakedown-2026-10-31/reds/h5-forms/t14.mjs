import {chromium} from "playwright";
const b=await chromium.launch();
const pg=await (await b.newContext({locale:"en",viewport:{width:900,height:1400}})).newPage();
const errs=[]; pg.on("console",m=>{if(["error","warning"].includes(m.type()))errs.push(m.text())}); pg.on("pageerror",e=>errs.push("PE "+e.message));
await pg.goto("http://localhost:4330/?lang=en");
await pg.locator("button[name=many]").click(); await pg.waitForTimeout(500);
const s=()=>pg.locator("[role=dialog]").first().innerText().then(x=>x.replace(/\n+/g," | ").slice(0,200));
console.log("open:",await s(), "rendered rows:",await pg.locator("[role=dialog] [role=checkbox],[role=dialog] label").count());
await pg.locator("[role=dialog] input").first().fill("Option 99"); await pg.waitForTimeout(400);
console.log("filtered:",await s());
await pg.evaluate(()=>window.log.length=0);
await pg.locator("[role=dialog] button",{hasText:/^All$/}).last().click(); await pg.waitForTimeout(600);
console.log("after All (filtered):",await s(), JSON.stringify(await pg.evaluate(()=>window.log)));
await pg.locator("[role=dialog] input").first().fill(""); await pg.waitForTimeout(400);
console.log("unfiltered:",await s());
await pg.locator("[role=dialog] button",{hasText:/^Invert$/}).click(); await pg.waitForTimeout(600);
console.log("invert:",await s(), JSON.stringify(await pg.evaluate(()=>window.log.slice(-1))));
await pg.screenshot({path:"shots/many-open.png"});
console.log(errs); await b.close();
