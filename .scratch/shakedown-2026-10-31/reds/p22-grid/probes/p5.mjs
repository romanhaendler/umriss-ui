import { open } from "./lib.mjs";
const p = await open("s=main", { width: 1100, height: 900 });
const setH = (h) => p.evaluate((h) => { document.getElementById("frame").style.height = h + "px"; }, h);
await p.evaluate(() => window.__t.setPage(4)); await p.waitForTimeout(200);
await p.evaluate(() => window.__t.focusCell("r35", "name")); await p.waitForTimeout(200);
await setH(800); await p.waitForTimeout(900);
console.log("grow w/ focus", await p.st());
await p.mouse.click(1050, 20); await p.waitForTimeout(900);
console.log("after blur", await p.st(), (await p.names())[0]);
await p.getByLabel("Rows per page").selectOption("25");
console.log("25", await p.st());
await setH(400); await p.waitForTimeout(900);
console.log("25 after resize", await p.st(), "view", await p.evaluate(()=>JSON.stringify(window.__view)));
await p.screenshot({ path: "shots/size25-400.png" });
await p.evaluate(() => window.__t.setPageSize("fit")); await p.waitForTimeout(500);
console.log("fit again", await p.st(), "view", await p.evaluate(()=>JSON.stringify(window.__view)));
await setH(200); await p.waitForTimeout(900); console.log("tiny", await p.st()); await p.screenshot({ path: "shots/tiny200.png" });
await setH(300); await p.waitForTimeout(900); console.log("300", await p.st());
console.log(p.errs);
await p.b.close();
